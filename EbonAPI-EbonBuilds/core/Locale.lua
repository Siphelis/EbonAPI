local FAMILY_CANON = {
    tank = "Tank", healer = "Healer", melee = "Melee", ranged = "Ranged",
    caster = "Caster", survival = "Survivability", survivability = "Survivability",
}
local FAMILY_GLOBAL = { Tank = "TANK", Healer = "HEALER", Melee = "MELEE", Ranged = "RANGED" }

function ns.FamilyName(key)
    if key == nil or key == "None" then return ns.L.FAMILY["No family"] end
    local canon = type(key) == "string" and FAMILY_CANON[key:lower()] or key
    local globalName = FAMILY_GLOBAL[canon]
    if globalName then
        local value = _G[globalName]
        if type(value) == "string" and value ~= "" then return value end
    end
    return ns.L.FAMILY[canon] or key
end
